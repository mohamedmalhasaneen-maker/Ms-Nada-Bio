  // تجميع القاموس في مصفوفة تعبيرات قياسية مدعومة ببادئات الحروف العربية (و، ف، ك، ب، ل)
  const COMPILED_RULES = RAW_DICTIONARY.map(function (entry) {
    const term = entry[0];
    const diacritized = entry[1];
    const escaped = term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const pattern = '(?<![\\u0621-\\u064A])([وفبلك])?' + escaped + '(?![\\u0621-\\u064A])';
    return {
      regex: new RegExp(pattern, 'g'),
      replace: function (_, prefix) {
        return (prefix || '') + diacritized;
      }
    };
  });

  // 2. معالجة الاختصارات اللاتينية والإنجليزية والأرقام الحيوية
  function normalizeAbbreviationsAndNumbers(text) {
    if (!text) return '';

    let out = text;

    // الفقرات برمزها وعلامتها
    out = out.replace(/\bC1\b/gi, 'الفَقْرَة العُنُقِيَّة الأُولَى سِي وَان');
    out = out.replace(/\bC2\b/gi, 'الفَقْرَة العُنُقِيَّة الثَّانِيَة سِي تُو');
    out = out.replace(/\bC3\b/gi, 'الفَقْرَة العُنُقِيَّة الثَّالِثَة');
    out = out.replace(/\bC4\b/gi, 'الفَقْرَة العُنُقِيَّة الرَّابِعَة');
    out = out.replace(/\bC5\b/gi, 'الفَقْرَة العُنُقِيَّة الخَامِسَة');
    out = out.replace(/\bC6\b/gi, 'الفَقْرَة العُنُقِيَّة السَّادِسَة');
    out = out.replace(/\bC7\b/gi, 'الفَقْرَة العُنُقِيَّة السَّابِعَة');

    out = out.replace(/\bT1\b/gi, 'الفَقْرَة الصَّدْرِيَّة الأُولَى');
    out = out.replace(/\bT12\b/gi, 'الفَقْرَة الصَّدْرِيَّة الثَّانِيَة عَشْرَة');
    out = out.replace(/\bT([3-9]|1[0-1])\b/gi, function (_, num) {
      return 'الفَقْرَة الصَّدْرِيَّة تِي ' + num;
    });

    out = out.replace(/\bL1\b/gi, 'الفَقْرَة القَطَنِيَّة الأُولَى');
    out = out.replace(/\bL5\b/gi, 'الفَقْرَة القَطَنِيَّة الخَامِسَة');
    out = out.replace(/\bL([2-4])\b/gi, function (_, num) {
      return 'الفَقْرَة القَطَنِيَّة إل ' + num;
    });

    // المواد الكيميائية الحيوية
    out = out.replace(/\bCa\s*(?:\^?2\+|\+2|2\+)/gi, 'أَيُونَات الكَالِسْيُوم الثُّنَائِيَّة');
    out = out.replace(/\bATP\b/g, 'جُزَيْئَات الطَّاقَة إِيه تِي بِي');
    out = out.replace(/\bADP\b/g, 'جُزَيْئَات إِيه دِي بِي');
    out = out.replace(/\bTMJ\b/gi, 'مَفْصِل الفَكّ الصَّدْغِي');
    out = out.replace(/\bDNA\b/gi, 'الحَمْض النَّوَوِي دِي إِنْ إِيه');
    out = out.replace(/\bRNA\b/gi, 'الحَمْض النَّوَوِي الرِّيبُوزِي آرْ إِنْ إِيه');

    // إحصائيات المنهج المصري
    out = out.replace(/\b206\b/g, 'مِائَتَانِ وَسِتّ');
    out = out.replace(/\b600\+/g, 'أَكْثَر مِنْ سِتِّمِائَة');
    out = out.replace(/\b620\b/g, 'سِتِّمِائَةٍ وَعِشْرُونَ');
    out = out.replace(/\b43\s*زوج/g, 'ثَلَاثَةٌ وَأَرْبَعُونَ زَوْجاً');
    out = out.replace(/\b12\s*زوج/g, 'اثْنَا عَشَرَ زَوْجاً');
    out = out.replace(/\b31\s*زوج/g, 'وَاحِدٌ وَثَلَاثُونَ زَوْجاً');
    out = out.replace(/\b33\s*فقرة/g, 'ثَلَاثٌ وَثَلَاثُونَ فَقْرَةً');
    out = out.replace(/\b26\s*عظمة/g, 'سِتٌّ وَعِشْرُونَ عَظْمَةً');
    out = out.replace(/\b80\s*عظمة/g, 'ثَمَانُونَ عَظْمَةً');
    out = out.replace(/\b126\s*عظمة/g, 'مِائَةٌ وَسِتٌّ وَعِشْرُونَ عَظْمَةً');
    out = out.replace(/\b1\s*عظمة/g, 'عَظْمَةٌ وَاحِدَة');
    out = out.replace(/\b2\s*عظمة/g, 'عَظْمَتَان');

    // تنظيف أو إزالة الكلمات الإنجليزية واللاتينية الموضوعة بين أقواس لتفادي تلعثم القارئ
    out = out.replace(/\s*\([A-Za-z\s,\.\-&/0-9]+\)/g, '');

    // إزالة الرموز الزخرفية وتنعيم علامات الترقيم لمنع الوقفات الطويلة
    out = out.replace(/[•★✓✗❖►◄]/g, '، ');
    out = out.replace(/[:\-–—|]/g, '، ');
    out = out.replace(/\s+/g, ' ').trim();

    return out;
  }

  // 3. تطبيق القاموس بالكامل على أي نص تشريحي
  function preparePhoneticAnatomicalText(rawText) {
    if (!rawText || typeof rawText !== 'string') return '';

    let text = normalizeAbbreviationsAndNumbers(rawText);

    // تطبيق قواعد التشكيل المجمعة
    for (let i = 0; i < COMPILED_RULES.length; i++) {
      const rule = COMPILED_RULES[i];
      text = text.replace(rule.regex, rule.replace);
    }

    // تنظيف الفواصل وتجنب الفواصل المتكررة
    text = text
      .replace(/([،.؛!؟])\s*/g, '$1 ')
      .replace(/\s+([،.؛!؟])/g, '$1')
      .replace(/،\s*،+/g, '، ')
      .replace(/\.\s*\.+/g, '. ')
      .replace(/\s+/g, ' ')
      .trim();

    return text;
  }

  // 4. تقسيم النصوص الطويلة ذكياً لمنع القطع وضمان اكتمال الجمل وانسيابيتها
  function splitTextIntoChunks(text, maxLen) {
    if (!text || typeof text !== 'string') return [];
    // زيادة الحد إلى 320 حرف لتمكين الجمل الكاملة المتماسكة وتقليل فواصل التقطيع
    const limit = maxLen || 320;

    const rawSentences = text.split(/(?<=[.!\n؟])\s+/);
    const result = [];
    let currentBlock = '';

    for (let i = 0; i < rawSentences.length; i++) {
      let sentence = rawSentences[i].trim();
      if (!sentence) continue;

      if (!currentBlock) {
        if (sentence.length <= limit) {
          currentBlock = sentence;
        } else {
          // الجملة بحد ذاتها أطول من الحد، تقسم عند الفواصل المنطقية
          const subClauses = splitLongSentenceByClauses(sentence, limit);
          result.push(...subClauses);
        }
      } else {
        if ((currentBlock + ' ' + sentence).length <= limit) {
          currentBlock += ' ' + sentence;
        } else {
          result.push(currentBlock);
          if (sentence.length <= limit) {
            currentBlock = sentence;
          } else {
            const subClauses = splitLongSentenceByClauses(sentence, limit);
            result.push(...subClauses);
            currentBlock = '';
          }
        }
      }
    }
    if (currentBlock) {
      result.push(currentBlock);
    }

    return result.length > 0 ? result : [text.trim()];
  }

  function splitLongSentenceByClauses(sentence, limit) {
    const clauses = sentence.split(/(?<=[،؛])\s+/);
    const res = [];
    let curr = '';

    for (let j = 0; j < clauses.length; j++) {
      const c = clauses[j].trim();
      if (!c) continue;
      if (!curr) {
        curr = c;
      } else if ((curr + ' ' + c).length <= limit) {
        curr += ' ' + c;
      } else {
        res.push(curr);
        curr = c;
      }
    }
    if (curr) res.push(curr);
    return res.length > 0 ? res : [sentence];
  }

  // 5. تقسيم المحتوى التشريحي إلى الأقسام الأربعة المطلوبة بدقة (الاسم، البيان والوظيفة، المعالم والتراكيب، أسرار الامتحان)
  function parseAnatomicalSentences(item) {
    if (!item) return [];

    const segments = [];

    function addSectionChunks(rawText, type, label) {
      if (!rawText || typeof rawText !== 'string') return;
      const trimmed = rawText.trim();
      if (!trimmed) return;

      const chunks = splitTextIntoChunks(trimmed, 320);
      chunks.forEach((chunk) => {
        const spoken = preparePhoneticAnatomicalText(chunk);
        if (spoken && spoken.trim()) {
          segments.push({
            id: `${type}_${segments.length}`,
            type: type, // 'name' | 'overview' | 'landmarks' | 'exam'
            label: label,
            rawText: chunk,
            spokenText: spoken
          });
        }
      });
    }

    // 1. الاسم باللغة العربية مع التمهيد
    const rawName = (item.name || '').replace(/\s*\([A-Za-z\s,\.\-&/0-9]+\)/g, '').trim() || 'عنصر تشريحي';

    // 2. قسم البيان والوظيفة بالكامل (Overview & Function)
    const overviewParts = [];
    if (item.classification) overviewParts.push(`التصنيف التشريحي: ${item.classification}.`);
    if (item.location) overviewParts.push(`الموقع: ${item.location}.`);
    if (item.functionDesc) overviewParts.push(item.functionDesc);
    if (item.primaryFunction) overviewParts.push(`الوظيفة الرئيسية: ${item.primaryFunction}.`);
    if (item.secondaryFunction) overviewParts.push(`الوظيفة الثانوية: ${item.secondaryFunction}.`);
    if (item.role && !item.functionDesc && !item.primaryFunction) overviewParts.push(`الوظيفة الحيوية: ${item.role}.`);

    // دمج اسم العنصر مع بداية الشرح مباشرة ليكون مسترسلاً وطبيعياً كشرح معلمة
    const introAndOverview = `${rawName}، ${overviewParts.join(' ')}`.trim();
    if (introAndOverview) {
      addSectionChunks(introAndOverview, 'overview', 'البيان والوظيفة');
    }

    // 3. قسم المعالم والتراكيب بالكامل (Landmarks & Structures)
    const landmarksParts = [];
    if (item.landmarks) landmarksParts.push(`المعالم التشريحية: ${item.landmarks}.`);
    if (item.structure) landmarksParts.push(`التركيب الدقيق: ${item.structure}.`);
    if (item.relations) landmarksParts.push(`العلاقات والاتصالات التشريحية: ${item.relations}.`);
    if (item.articulations) landmarksParts.push(`التأثير والتمفصل: ${item.articulations}.`);
    if (item.origin) landmarksParts.push(`منشأ العضلة: ${item.origin}.`);
    if (item.insertion) landmarksParts.push(`ارتكاز العضلة: ${item.insertion}.`);
    if (item.action) landmarksParts.push(`الحركة والعمل: ${item.action}.`);
    if (item.innervation) landmarksParts.push(`التعصيب العصبي: ${item.innervation}.`);
    if (item.muscleAttachments) landmarksParts.push(`العضلات المتصلة: ${item.muscleAttachments}.`);
    if (landmarksParts.length > 0) {
      addSectionChunks(landmarksParts.join(' '), 'landmarks', 'المعالم والتراكيب');
    }

    // 4. قسم أسرار الامتحان بالكامل (Exam Secrets & Curriculum)
    const examParts = [];
    if (item.curriculumImportance) examParts.push(`الأهمية المنهجية: ${item.curriculumImportance}.`);
    if (item.examNote) examParts.push(item.examNote);
    if (examParts.length > 0) {
      addSectionChunks(examParts.join(' '), 'exam', 'أسرار الامتحان');
    }

    return segments;
  }

  window.BioAudioDictionary = {
    preparePhoneticAnatomicalText: preparePhoneticAnatomicalText,
    parseAnatomicalSentences: parseAnatomicalSentences,
    normalizeAbbreviationsAndNumbers: normalizeAbbreviationsAndNumbers,
    splitTextIntoChunks: splitTextIntoChunks
  };
